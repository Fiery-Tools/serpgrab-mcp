// serpgrab JSON (SerpApi's format) -> compact text for a model's context. Pure functions, no I/O.

/** The scalar fields of a block (strings and numbers), skipping links, ids and images. */
function scalars(obj, skip = []) {
  const out = [];
  for (const [k, v] of Object.entries(obj ?? {})) {
    if (skip.includes(k) || /(^|_)(link|links|id|kgmid|image|images|thumbnail|serpapi_link)s?$/.test(k)) continue;
    if (typeof v === 'string' || typeof v === 'number') out.push(`${k.replace(/_/g, ' ')}: ${v}`);
  }
  return out;
}

/** The AI Overview's text_blocks as plain text (headings, paragraphs, lists). */
export function overviewText(ai) {
  const out = [];
  for (const b of ai?.text_blocks ?? []) {
    if (b.type === 'heading') out.push(`### ${b.snippet}`);
    else if (b.type === 'list') for (const li of b.list ?? []) out.push(`- ${li.title ? `${li.title}: ` : ''}${li.snippet ?? ''}`);
    else if (b.snippet) out.push(b.snippet);
  }
  return out.join('\n');
}

function placeLine(p, i) {
  const bits = [p.type, p.rating != null ? `${p.rating}★${p.reviews != null ? ` (${p.reviews} reviews)` : ''}` : null, p.price];
  const lines = [`${i + 1}. ${p.title || '(no name)'}${bits.some(Boolean) ? ` - ${bits.filter(Boolean).join(', ')}` : ''}`];
  const more = [p.address, p.phone, p.hours || p.open_state, p.website].filter(Boolean);
  if (more.length) lines.push(`   ${more.join(' · ')}`);
  return lines;
}

/**
 * One or more Google web results pages as text. `pages` is the list of parsed /search.json
 * responses in order; blocks that only appear once (AI Overview, answer box, knowledge graph,
 * local pack, People also ask) are taken from the first page.
 */
export function formatWeb({ query, country, pages, requested = pages.length, stoppedEarly = null }) {
  const first = pages[0] ?? {};
  const L = [`Google results for "${query}" (country: ${country}, via serpgrab)`, ''];

  const overview = overviewText(first.ai_overview);
  if (overview) L.push('## AI Overview (generated by Google; may contain mistakes)', '', overview, '');

  if (first.answer_box) {
    const ab = first.answer_box;
    L.push(`## Answer box${ab.type ? ` (${ab.type.replace(/_/g, ' ')})` : ''}`, '');
    L.push(...scalars(ab, ['type']).slice(0, 12), '');
  }

  if (first.knowledge_graph) {
    const kg = first.knowledge_graph;
    L.push(`## Knowledge panel: ${kg.title ?? ''}`.trimEnd(), '');
    L.push(...scalars(kg, ['title', 'entity_type']).slice(0, 12), '');
  }

  const places = first.local_results?.places ?? [];
  if (places.length) L.push('## Local results', '', ...places.flatMap(placeLine), '');

  const seen = new Set();
  const results = [];
  for (const page of pages) {
    for (const r of page.organic_results ?? []) {
      if (!r.link || seen.has(r.link)) continue;
      seen.add(r.link);
      results.push(r);
    }
  }
  L.push('## Results', '');
  results.forEach((r, i) => {
    L.push(`${i + 1}. ${r.title || '(no title)'} - ${r.link}`);
    if (r.snippet) L.push(`   ${r.date ? `${r.date} · ` : ''}${r.snippet}`);
  });
  if (!results.length) L.push('(no results)');

  const ads = pages.flatMap((p) => p.ads ?? []);
  if (ads.length) {
    L.push('', '## Ads', '');
    for (const a of ads) L.push(`- ${a.title || '(no title)'} - ${a.link}`);
  }

  const questions = (first.related_questions ?? []).map((q) => q.question).filter(Boolean);
  if (questions.length) L.push('', '## People also ask', '', ...questions.map((q) => `- ${q}`));

  let summary = `${results.length} results from ${pages.length} of ${requested} page${requested > 1 ? 's' : ''}`;
  if (stoppedEarly) summary += ` (${stoppedEarly})`;
  L.push('', `${summary}.`);
  return L.join('\n');
}

/** A Google Maps results page as text. */
export function formatMaps({ query, country, data, page = 1 }) {
  const places = data.local_results ?? [];
  const L = [`Google Maps results for "${query}" (country: ${country}, page ${page}, via serpgrab)`, ''];
  if (!places.length) L.push('(no places)');
  places.forEach((p, i) => {
    L.push(...placeLine(p, (page - 1) * 20 + i));
    const g = p.gps_coordinates;
    if (g) L.push(`   ${g.latitude.toFixed(5)},${g.longitude.toFixed(5)}${p.place_id ? ` · place_id ${p.place_id}` : ''}`);
  });
  L.push('', `${places.length} places${data.serpapi_pagination?.next ? `; more on page ${page + 1}` : ''}.`);
  return L.join('\n');
}
